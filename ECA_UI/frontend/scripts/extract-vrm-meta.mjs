import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const frontendRoot = resolve(scriptDir, '..')
const modelsDir = resolve(frontendRoot, 'src', 'asset', 'models')
const outDir = resolve(frontendRoot, 'src', 'avatar')
const outFile = join(outDir, 'vrmManifest.ts')

// ── VRM 0.0 preset name categories ──────────────────────────────────────

const EMOTION_PRESETS = new Set(['joy', 'angry', 'sorrow', 'fun', 'neutral'])
const VISEME_PRESETS = new Set(['a', 'i', 'u', 'e', 'o'])
const BLINK_PRESETS = new Set(['blink', 'blink_l', 'blink_r'])
const LOOKAT_PRESETS = new Set(['lookup', 'lookdown', 'lookleft', 'lookright'])

function classify(presetName) {
  if (!presetName || presetName === 'unknown') return 'custom'
  if (EMOTION_PRESETS.has(presetName)) return 'emotion'
  if (VISEME_PRESETS.has(presetName)) return 'viseme'
  if (BLINK_PRESETS.has(presetName)) return 'blink'
  if (LOOKAT_PRESETS.has(presetName)) return 'lookAt'
  return 'custom'
}

// ── Emit-friendly name (lowercase, no special chars) ────────────────────

function toEmitName(presetName, fallback) {
  if (presetName && presetName !== 'unknown') return presetName
  return fallback.toLowerCase().replace(/[^a-z0-9_]/gi, '_')
}

/** Sanitize a filename stem into a valid JS identifier. */
function toVarName(modelId) {
  return modelId.replace(/[^a-zA-Z0-9_$]/g, '_').replace(/^(\d)/, '_$1')
}

// ── GLB parser ──────────────────────────────────────────────────────────

function parseVRMBlendShapes(filePath) {
  const buf = readFileSync(filePath)
  if (buf.readUInt32LE(0) !== 0x46546C67) {
    console.warn(`  [warn] not a GLB file`)
    return null
  }
  const jsonLen = buf.readUInt32LE(12)
  const jsonData = buf.slice(20, 20 + jsonLen)
  const glb = JSON.parse(jsonData.toString('utf8'))

  const ext = glb.extensions?.VRM
  if (!ext) {
    console.warn(`  [warn] no VRM extension`)
    return null
  }
  return ext.blendShapeMaster?.blendShapeGroups || []
}

// ── Main ────────────────────────────────────────────────────────────────

const vrmFiles = readdirSync(modelsDir).filter((f) => f.endsWith('.vrm'))
if (vrmFiles.length === 0) {
  console.log('No .vrm files found in', modelsDir)
  process.exit(0)
}

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })

const manifest = /** @type {Record<string, object>} */ ({})

for (const file of vrmFiles) {
  const modelId = basename(file, '.vrm')
  const filePath = join(modelsDir, file)
  console.log(`[vrm-meta] ${modelId} ...`)

  const groups = parseVRMBlendShapes(filePath)
  if (!groups) {
    // `groups` is a COUNT everywhere else — emitting `[]` here made the fallback
    // a different shape from the success path, which no type could describe.
    manifest[modelId] = { groups: 0, emotions: [], visemes: [], blinks: [], lookAts: [], customs: [] }
    continue
  }

  /** @type {Array<{name:string,emit:string,presetName:string|null,category:string,bindCount:number,isBinary:boolean}>} */
  const emotions = []
  const visemes = []
  const blinks = []
  const lookAts = []
  const customs = []

  for (const g of groups) {
    const cat = classify(g.presetName)
    const entry = {
      name: g.name,
      emit: toEmitName(g.presetName, g.name),
      presetName: g.presetName ?? null,
      category: cat,
      bindCount: (g.binds || []).length,
      isBinary: !!g.isBinary,
    }
    if (cat === 'emotion') emotions.push(entry)
    else if (cat === 'viseme') visemes.push(entry)
    else if (cat === 'blink') blinks.push(entry)
    else if (cat === 'lookAt') lookAts.push(entry)
    else customs.push(entry)
  }

  manifest[modelId] = {
    groups: groups.length,
    emotions,
    visemes,
    blinks,
    lookAts,
    customs,
  }

  console.log(
    `  ${emotions.length}E ${visemes.length}V ${blinks.length}B ${lookAts.length}L ${customs.length}C`,
  )
}

// Write as TypeScript module (verbatimModuleSyntax + no resolveJsonModule)
const lines = [
  '/* eslint-disable */',
  '/** Generated by scripts/extract-vrm-meta.mjs — DO NOT EDIT. */',
  '',
]
for (const [modelId, data] of Object.entries(manifest)) {
  const varName = toVarName(modelId)
  lines.push(`export const ${varName} = ${JSON.stringify(data)} as const`)
  lines.push('')
}
const allIds = Object.keys(manifest)
lines.push(`export const allModelIds = ${JSON.stringify(allIds)} as const`)
lines.push('')
lines.push('/** One VRM blendShape group, flattened. */')
lines.push('export type VrmBlendShape = {')
lines.push('  readonly name: string')
lines.push('  readonly emit: string')
lines.push('  readonly presetName: string | null')
lines.push("  readonly category: 'emotion' | 'viseme' | 'blink' | 'lookAt' | 'custom'")
lines.push('  readonly bindCount: number')
lines.push('  readonly isBinary: boolean')
lines.push('}')
lines.push('')
lines.push('/**')
lines.push(' * Structural on purpose. This used to be `typeof <first model>`, which baked')
lines.push(" * that one model's blendShape counts into the type as literals — every other")
lines.push(' * model then failed to be a `VrmManifestEntry` (14 is not assignable to 18).')
lines.push(' */')
lines.push('export type VrmManifestEntry = {')
lines.push('  readonly groups: number')
lines.push('  readonly emotions: readonly VrmBlendShape[]')
lines.push('  readonly visemes: readonly VrmBlendShape[]')
lines.push('  readonly blinks: readonly VrmBlendShape[]')
lines.push('  readonly lookAts: readonly VrmBlendShape[]')
lines.push('  readonly customs: readonly VrmBlendShape[]')
lines.push('}')
lines.push('')
lines.push('export function getManifest(modelId: string): VrmManifestEntry | null {')
lines.push('  const key = modelId.toLowerCase()')
for (const id of allIds) {
  const varName = toVarName(id)
  // Compare against the LOWERCASED id: `key` is already lowercased, so a model
  // file with any uppercase in its name (Con-Gai-Khang) could never match.
  lines.push(`  if (key === '${id.toLowerCase()}') return ${varName}`)
}
lines.push('  return null')
lines.push('}')
lines.push('')

writeFileSync(outFile, lines.join('\n'))
console.log(`\n[vrm-meta] wrote ${allIds.length} model(s) → ${outFile}`)
